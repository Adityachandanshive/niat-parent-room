export function t(locale: Locale, key: string): string {
  const entry = strings[key]
  if (!entry) return key
  return entry[locale] || entry.en || key
}

export function getConcernLabel(locale: Locale, concern: string): string {
  return t(locale, `concern.${concern}`)
}

export function formatReportDesc(
  locale: Locale,
  child: string,
  campus: string,
): string {
  return t(locale, 'intake.ready_desc')
    .replace('{child}', child)
    .replace('{campus}', campus)
}
